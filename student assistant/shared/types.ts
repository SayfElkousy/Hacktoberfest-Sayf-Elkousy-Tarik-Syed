// Types shared by the server, the student site and the dashboard API.

/** How a step gets confirmed. Gemma picks one per step when it reads the procedure. */
export type CheckMode = 'camera' | 'measure' | 'sensor' | 'ask';

export interface LabComponent {
  id: string;
  name: string;
  /** What it looks like, so the camera check knows what to search for. */
  lookFor: string;
  quantity: number;
}

export interface MeasurementTarget {
  kind: 'angle' | 'length';
  /** The thing being measured, e.g. "the track". */
  subject: string;
  /** The value the procedure asks for, or null when it doesn't give one. */
  target: number | null;
  tolerance: number | null;
  unit: 'deg' | 'cm';
}

export interface LabQuestion {
  id: string;
  question: string;
  /** What a good answer contains, used to grade the student's reply. */
  expected: string;
  kind: 'observation' | 'comprehension';
}

export interface LabStep {
  id: string;
  title: string;
  /** Read aloud and shown on screen. */
  instruction: string;
  mode: CheckMode;
  /** What a correctly finished step looks like on camera. */
  lookFor: string;
  /** Asked instead when the camera can't tell. */
  confirmQuestion: string;
  measurement: MeasurementTarget | null;
  /** Ids of the components this step involves, which the camera checks focus on. */
  tracks: string[];
  questions: LabQuestion[];
  safety: string | null;
}

export interface LabPlan {
  title: string;
  subject: string;
  objective: string;
  components: LabComponent[];
  steps: LabStep[];
}

export type LabStatus = 'preparing' | 'ready' | 'failed' | 'ended';

/** A lab group from the dashboard. */
export interface LabTeam {
  id: string;
  name: string;
}

/** One team's progress, worked out from its members. A team moves as its furthest member does. */
export interface TeamProgress extends LabTeam {
  members: string[];
  online: number;
  stepsDone: number;
  totalSteps: number;
  finished: boolean;
  helpRequested: boolean;
  alert: string | null;
}

export interface Lab {
  id: string;
  /** The join code, generated by the dashboard. */
  code: string;
  procedure: string;
  teams: LabTeam[];
  /** The dashboard's own steps, when it has them, so plan steps match its steps one to one. */
  knownSteps: string[] | null;
  status: LabStatus;
  /** Set when the dashboard replaced this code: students already in keep going, new ones can't join. */
  closed?: boolean;
  plan: LabPlan | null;
  error: string | null;
  createdAt: number;
}

export type StepStatus = 'pending' | 'active' | 'passed' | 'needs_attention' | 'skipped';
export type ComponentStatus = 'unknown' | 'seen' | 'confirmed' | 'missing';
/** Where a recorded value came from. */
export type DataSource = 'camera' | 'sensor' | 'student';

export interface StepProgress {
  stepId: string;
  status: StepStatus;
  attempts: number;
  lastFeedback: string | null;
}

export interface MeasurementRecord {
  stepId: string;
  label: string;
  value: number;
  unit: string;
  target: number | null;
  withinTolerance: boolean | null;
  source: DataSource;
  at: number;
}

export interface AnswerRecord {
  promptId: string;
  stepId: string | null;
  question: string;
  answer: string;
  correct: boolean;
  feedback: string;
  askedBy: 'teacher' | 'procedure';
  at: number;
}

export type Phase = 'components' | 'steps' | 'done';

export interface StudentProgress {
  id: string;
  name: string;
  labId: string;
  teamId: string | null;
  teamName: string | null;
  joinedAt: number;
  lastSeen: number;
  online: boolean;
  phase: Phase;
  currentStep: number;
  components: Record<string, ComponentStatus>;
  steps: StepProgress[];
  measurements: MeasurementRecord[];
  answers: AnswerRecord[];
  helpRequested: boolean;
  /** Set when Gemma thinks the teacher should look, e.g. a safety problem. */
  alert: string | null;
}

/** A question waiting for a student, pushed live or taken from the procedure. */
export interface Prompt {
  id: string;
  question: string;
  expected: string | null;
  kind: 'observation' | 'comprehension' | 'custom';
  askedBy: 'teacher' | 'procedure';
  stepId: string | null;
  /** True when the answer decides the step, so a right answer passes it. */
  confirmsStep: boolean;
  /** True when this came from pressing Next, so answering carries on to the next step. */
  continuesStep: boolean;
}

/** What the student's browser sees: the grading notes stay on the server. */
export type PublicPrompt = Omit<Prompt, 'expected'>;

/** The lab as students receive it, with the expected answers removed. */
export interface StudentLab {
  id: string;
  plan: Omit<LabPlan, 'steps'> & {
    steps: (Omit<LabStep, 'questions'> & { questionCount: number })[];
  };
}

export interface StudentSession {
  student: StudentProgress;
  lab: StudentLab;
  pending: PublicPrompt[];
}

export type StudentEvent =
  | { type: 'prompt'; prompt: PublicPrompt }
  | { type: 'lab-ended' };

export type DashboardEvent =
  | { type: 'lab'; lab: Lab }
  | { type: 'student'; student: StudentProgress };

/** A point in Gemma's 0–1000 image coordinates. */
export interface GridPoint {
  x: number;
  y: number;
}

/** A box in Gemma's 0–1000 image coordinates. */
export interface GridBox {
  left: number;
  top: number;
  right: number;
  bottom: number;
}

export interface FrameSize {
  width: number;
  height: number;
}

/** A webcam frame: base64 JPEG without the data: prefix. */
export interface Frame extends FrameSize {
  image: string;
}

export interface IdentifiedComponent {
  id: string;
  visible: boolean;
  box: GridBox | null;
}

export interface IdentifyResult {
  items: IdentifiedComponent[];
  components: Record<string, ComponentStatus>;
}

export type Verdict = 'correct' | 'incorrect' | 'unclear';

export interface CheckResult {
  verdict: Verdict;
  feedback: string;
  /** Present when the camera couldn't tell and the student should be asked instead. */
  followUp: PublicPrompt | null;
}

export interface MeasureResult {
  measured: boolean;
  kind: 'angle' | 'length';
  value: number | null;
  unit: string;
  target: number | null;
  withinTolerance: boolean | null;
  feedback: string;
  /** Points Gemma used, so the site can draw what was measured. */
  line: { start: GridPoint; end: GridPoint } | null;
}

/** What advancing returns: the next question, or the updated student. */
export interface NextResult {
  student: StudentProgress;
  prompt: PublicPrompt | null;
}

export interface SensorResult {
  count: number;
  mean: number;
  min: number;
  max: number;
  unit: string;
  feedback: string;
}

export interface AnswerResult {
  correct: boolean;
  feedback: string;
}
